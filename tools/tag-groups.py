if __name__ == '__main__':
    import sys, collections
    if len(sys.argv) < 2:
        print(f'도안 {len(G)}개 · 태그 {sum(len(v) for v in G.values())}개')
        print('사용법: python3 tools/tag-groups.py <태그목록파일>')
        raise SystemExit(0)
    lines = [l.strip() for l in open(sys.argv[1], encoding='utf-8') if l.strip()]
    verses = [[t.strip() for t in l.split(',') if t.strip()] for l in lines]
    alias = {}
    for mark, tags in G.items():
        for t in tags:
            if t in alias:
                print(f'⚠ 중복 배정: {t} → {alias[t]} / {mark}')
            alias[t] = mark
    cov = sum(1 for v in verses if any(t in alias for t in v))
    drawn = sum(1 for m in G if m in MARK)
    print(f'묶음 {len(G)}개 (그린 것 {drawn}개) · 별칭 {len(alias)}개')
    print(f'그림이 붙는 말씀: {cov}/{len(verses)} ({cov*100//len(verses)}%)')
    miss = collections.Counter(t for v in verses if not any(t in alias for t in v) for t in v)
    if miss:
        print('안 덮인 태그:', ', '.join(f'{t}({n})' for t, n in miss.most_common(30)))
