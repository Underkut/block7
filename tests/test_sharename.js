// 공유 이미지 저장 파일명 (v26-0812-2)
//
// 파일명 가운데 장절 숫자의 **자리수**를 맞춘다. 자리수는 "그 자리에 올 수 있는
// 가장 큰 수"에 맞춘다 — 더 늘리면 0 만 길어지고, 모자라면 이름순 정렬이 어긋난다.
//
//   장 : 시편만 3자리(150장까지) · 나머지 성경은 2자리(가장 긴 이사야가 66장)
//   절 : 시편 119장만 3자리(176절까지) · 나머지는 모두 2자리
//        (100절을 넘는 장은 시편 119장 하나뿐. 그다음이 민수기 7장 89절)
//
// 이 규칙이 있기 전에는 ':' 만 지우고 숫자를 있는 그대로 붙여서 4:6 이 '46' 이
// 되었고, 파일을 이름순으로 늘어놓으면 4:6 이 15:29 보다 뒤로 갔다.
//
// ⚠️ 여기서 제일 미끄러지기 쉬운 곳: **책 이름에도 숫자가 있다.**
//    '요한1서 5:14' 에서 첫 숫자(1)를 장으로 보면 안 된다. _bookOfRef 와 같이
//    ':' 까지 확인해야 한다. 이 파일이 그것을 고정한다.
const { slice, makeScorer } = require('./_load');
const sc = makeScorer();

// 시편인지 가려내려면 _bookCanon 이 있어야 한다 ('시' 같은 약칭도 펴서 견준다)
eval(
  slice('const _REF_ABBR2FULL=', 'function _refNorm(') +
  slice('// ── 성경책 이름 하나로 모으기 ──', '// verses를 keyFn 기준으로 묶어') +
  slice('// 장절 숫자의 자리수를 맞춘다', 'function _vfShareImage(') +
  ';Object.assign(globalThis,{_bookCanon,_refDigitsPad,_shareFileName});'
);

// 오늘 날짜는 파일명 뒤에 붙으므로, 검사할 때는 그 부분을 떼고 본다
const stamp = (() => {
  const d = new Date(), p = n => String(n).padStart(2, '0');
  return `${String(d.getFullYear()).slice(2)}${p(d.getMonth() + 1)}${p(d.getDate())}`;
})();
const nameOf = ref => _shareFileName({ ref });
const midOf = ref => nameOf(ref).replace(/^BLOCK7_/, '').replace(new RegExp(`_${stamp}\\.png$`), '');
const numOf = ref => _refDigitsPad(ref).num;

// ═══ 1. 장 자리수 ═══
console.log('시나리오 1 — 장(chapter) 자리수');
{
  // 1-2 시편이 아닌 성경은 2자리
  sc.eq('창세기 4장 → 04', numOf('창세기 4:6').slice(0, 2), '04');
  sc.eq('사무엘상 15장 → 15', numOf('사무엘상 15:29').slice(0, 2), '15');
  sc.eq('이사야 66장 → 66', numOf('이사야 66:1').slice(0, 2), '66');
  sc.eq('요한복음 1장 → 01', numOf('요한복음 1:1').slice(0, 2), '01');
  // 1-1 시편만 3자리
  sc.eq('시편 23장 → 023', numOf('시편 23:1').slice(0, 3), '023');
  sc.eq('시편 1장 → 001', numOf('시편 1:1').slice(0, 3), '001');
  sc.eq('시편 119장 → 119', numOf('시편 119:1').slice(0, 3), '119');
  sc.eq('시편 150장 → 150', numOf('시편 150:6').slice(0, 3), '150');
  sc.eq("약칭 '시' 도 시편으로 본다", numOf('시 23:1'), '02301');
}

// ═══ 2. 절 자리수 ═══
console.log('\n시나리오 2 — 절(verse) 자리수');
{
  // 2-2 시편 119장이 아니면 모두 2자리
  sc.eq('창세기 4:6 → 0406', numOf('창세기 4:6'), '0406');
  sc.eq('사무엘상 15:29 → 1529', numOf('사무엘상 15:29'), '1529');
  sc.eq('민수기 7:89 → 0789', numOf('민수기 7:89'), '0789');
  sc.eq('시편 23:1 도 절은 2자리', numOf('시편 23:1'), '02301');
  sc.eq('시편 150:6 도 절은 2자리', numOf('시편 150:6'), '15006');
  // 2-1 시편 119장만 3자리
  sc.eq('시편 119:176 → 119176', numOf('시편 119:176'), '119176');
  sc.eq('시편 119:11 → 119011', numOf('시편 119:11'), '119011');
  sc.eq('시편 119:9 → 119009', numOf('시편 119:9'), '119009');
  // 다른 성경의 119장은 3자리가 아니다 (시편만 그렇다)
  sc.eq('시편이 아닌 119장은 없지만 규칙은 2자리',
        numOf('창세기 11:9'), '1109');
}

// ═══ 3. ⚠️ 책 이름 속 숫자를 장으로 오해하지 않는다 ═══
console.log('\n시나리오 3 — 책 이름에 숫자가 있는 경우');
{
  sc.eq('요한1서 5:14 의 책', _refDigitsPad('요한1서 5:14').book, '요한1서');
  sc.eq('요한1서 5:14 의 장절', numOf('요한1서 5:14'), '0514');
  sc.eq('요한2서 1:6 의 책', _refDigitsPad('요한2서 1:6').book, '요한2서');
  sc.eq('요한2서 1:6 의 장절', numOf('요한2서 1:6'), '0106');
  sc.eq('고린도전서 15:20', numOf('고린도전서 15:20'), '1520');
}

// ═══ 4. 절이 여럿인 표기 ═══
console.log('\n시나리오 4 — 절이 하나가 아닐 때');
{
  sc.eq('요한복음 1:1,14 → 0101,14', numOf('요한복음 1:1,14'), '0101,14');
  sc.eq('고린도전서 15:3,4 → 1503,04', numOf('고린도전서 15:3,4'), '1503,04');
  sc.eq('시편 23:1-6 → 02301-06', numOf('시편 23:1-6'), '02301-06');
  sc.eq('시편 119:9-16 은 절이 3자리', numOf('시편 119:9-16'), '119009-016');
  sc.eq('빈칸이 섞여도', numOf('시편 23 : 1, 6'), '02301,06');
}

// ═══ 5. 파일명 전체 ═══
console.log('\n시나리오 5 — 실제로 저장되는 이름');
{
  sc.eq('창세기 4:6', midOf('창세기 4:6'), '창세기_0406');
  sc.eq('시편 119:176', midOf('시편 119:176'), '시편_119176');
  sc.eq('요한복음 1:1,14', midOf('요한복음 1:1,14'), '요한복음_0101,14');
  sc.eq('앞뒤에 BLOCK7 과 날짜', /^BLOCK7_.+_\d{6}\.png$/.test(nameOf('창세기 4:6')), true);
  // 이름순 정렬이 장절 순서와 맞아야 한다 — 이게 이 작업의 목적이다
  sc.eq('시편이 아닌 책: 이름순 = 장절순',
        ['창세기 11:9', '창세기 4:6', '창세기 15:29', '창세기 4:26'].map(midOf).sort(),
        ['창세기_0406', '창세기_0426', '창세기_1109', '창세기_1529']);
  sc.eq('시편: 이름순 = 장절순',
        ['시편 119:176', '시편 4:6', '시편 23:1', '시편 119:11', '시편 100:5'].map(midOf).sort(),
        ['시편_00406', '시편_02301', '시편_10005', '시편_119011', '시편_119176']);
}

// ═══ 6. 알아볼 수 없는 표기는 그대로 둔다 ═══
console.log('\n시나리오 6 — 장:절 꼴이 아닐 때');
{
  sc.eq('절이 없으면 못 편다', _refDigitsPad('시편 119'), null);
  sc.eq('그래도 파일명은 만든다', midOf('시편 119'), '시편_119');
  sc.eq('빈 장절도 안전', _refDigitsPad(''), null);
  sc.eq('ref 가 없으면 verse', midOf(''), 'verse');
  sc.eq('구절 자체가 없어도 안전', /^BLOCK7_verse_/.test(_shareFileName(null)), true);
  // 파일명에 못 쓰는 글자는 빼고, 빈칸은 밑줄로
  sc.eq("':' 는 남지 않는다", midOf('창세기 4:6').includes(':'), false);
  sc.eq('빈칸은 밑줄', midOf('창세기 4:6').includes(' '), false);
}

sc.done();
