// 일정 칩 이름 길이 (B2, HB 2026-10-27) — '5자' 로 정했는데 칩마다 길이가 들쭉날쭉했다.
//   까닭: 시각 칸이 빈 일정은 이름 앞에 시각을 글자로 적어 두었고('12.3 서희나 …'), 그 숫자까지 5자로 세서
//   '12.3 …' · '18 태원…' 처럼 이름이 거의 안 남았다. 지킬 것: 맨 앞 시각 한 덩이는 보이되 세지 않는다.
const { slice, makeScorer } = require('./_load');
const sc = makeScorer();
global.ST = { settings: { evChipMax: 5 } };
eval(slice('function _evChipN(){', '// 미리보기 —'));
sc.eq('시각 칸이 따로 있는 보통 이름은 5자', _evChipCut('예배팀 연습 리허설'), '예배팀 연…');
sc.eq('⭐ 앞에 적은 시각(12.3)은 세지 않는다', _evChipCut('12.3 서희나+리더십 식사'), '12.3 서희나+리…');
sc.eq('⭐ 시만 적은 것(18)도', _evChipCut('18 태원고 입시 설명회'), '18 태원고 입…');
sc.eq('콜론 시각 · 범위도 한 덩이', _evChipCut('19:30~21 청년부 수련회 준비'), '19:30~21 청년부 수…');
sc.eq('짧은 이름은 그대로', _evChipCut('18 셀'), '18 셀');
sc.eq('숫자만 있는 이름은 건드리지 않는다', _evChipCut('2026'), '2026');
sc.eq('25 처럼 시각이 아닌 숫자는 이름으로 센다', _evChipCut('25 주년 감사 예배'), '25 주년…');
sc.eq('여러 날 꼬리표 없는 빈 이름', _evChipCut(''), '');
ST.settings.evChipMax = 12;
sc.eq('12자 그대로', _evChipCut('12.3 서희나+리더십 식사 @ 두향'), '12.3 서희나+리더십 식사 @…');
sc.done();
